// node tools/live/make_sample_usframes.mjs  -> assets/usframes/sample-synthetic/ (24 synthetic 160x120 frames)
// Synthetic only: a speckled fan with a dark "vessel" ellipse that grows and shrinks along the stack.
// PNG is written with node:zlib (grayscale, 8 bit). Frame extension is recorded in stack.json "ext".
import { deflateSync } from "node:zlib";
import { mkdirSync, writeFileSync } from "node:fs";
const W = 160, H = 120, N = 24;
const out = new URL("../../assets/usframes/sample-synthetic/", import.meta.url).pathname;
mkdirSync(out + "frames", { recursive: true });
let seed = 12345;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);
const crcT = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc = (b) => { let c = 0xffffffff; for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (t, d) => { const b = Buffer.alloc(12 + d.length); b.writeUInt32BE(d.length, 0); b.write(t, 4, "latin1"); d.copy(b, 8); b.writeUInt32BE(crc(b.subarray(4, 8 + d.length)), 8 + d.length); return b; };
function png(gray) {
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4); ihdr[8] = 8; ihdr[9] = 0;
  const raw = Buffer.alloc((W + 1) * H);
  for (let y = 0; y < H; y++) { raw[y * (W + 1)] = 0; gray.copy(raw, y * (W + 1) + 1, y * W, (y + 1) * W); }
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}
const labels = [];
for (let f = 0; f < N; f++) {
  const t = f / (N - 1), g = Buffer.alloc(W * H);
  const r = 12 + 14 * Math.sin(Math.PI * t), cx = 80 + 18 * (t - 0.5), cy = 58;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const dx = x - 80, dy = y - 4, rad = Math.hypot(dx, dy), ang = Math.atan2(dx, dy) * 180 / Math.PI;
    let v = 0;
    if (Math.abs(ang) < 38 && rad < 112 && rad > 6) {
      const speck = 0.35 + 0.65 * rnd() * rnd() * 2.2;
      v = 150 * Math.exp(-rad / 90) * speck + 20 + 25 * Math.exp(-((y - 85) ** 2) / 200);
      if (((x - cx) / r) ** 2 + ((y - cy) / (r * 0.7)) ** 2 < 1) v *= 0.12;
    }
    g[y * W + x] = Math.round(Math.min(255, v) / 12) * 12; // quantised: keeps the sample small
  }
  writeFileSync(`${out}frames/${String(f).padStart(3, "0")}.png`, png(g));
  const poly = Array.from({ length: 16 }, (_, i) => { const a = (i / 16) * Math.PI * 2; return [+((cx + r * Math.cos(a)) / W).toFixed(4), +((cy + r * 0.7 * Math.sin(a)) / H).toFixed(4)]; });
  labels.push([{ key: "vessel", name: "Synthetic vessel", poly }]);
}
writeFileSync(out + "stack.json", JSON.stringify({
  version: 1, id: "sample-synthetic", title: "Synthetic sample", modality: "ultrasound", ext: "png",
  source: "Generated by tools/live/make_sample_usframes.mjs (not a patient scan)", license: "CC0-1.0",
  segment: "trunk", side: null, frac: [0.2, 0.3], frames: N, width: W, height: H, labels,
}));
console.log("wrote", N, "frames to", out);
